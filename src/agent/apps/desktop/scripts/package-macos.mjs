import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {readFile} from 'node:fs/promises';
import {installBoundedMacSigningWalk} from './macos-sign-walk.mjs';
import {prepareMacInstaller} from './macos-installer.mjs';
import {stageDevelopmentResources} from './development-resources.mjs';
import {stageCompactResources,verifyCompactServer} from './compact-resources.mjs';
import {writeStandaloneInstallerConfig} from './standalone-installer-config.mjs';
if(process.platform!=='darwin')throw Error('Build and qualify the macOS installer on macOS.');
await installBoundedMacSigningWalk();
const {Arch,build,Platform}=await import('electron-builder');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const argument=name=>{const i=process.argv.indexOf(name);return i<0?undefined:process.argv[i+1];};
const runtimePkg=argument('--runtime'),runtimeSha256=argument('--sha256'),arch=argument('--arch')??process.arch;
if(!['arm64','x64'].includes(arch)||arch!==process.arch)throw Error('Mac qualification requires its native architecture');
if(arch==='arm64'&&(!runtimePkg||!runtimeSha256))throw Error('Use --runtime <verified Apple Silicon PKG> --sha256 <pinned hash>');
const version=JSON.parse(await readFile(path.join(root,'package.json'),'utf8')).version;
const output=argument('--out')??path.join(root,'release');
const development=await stageDevelopmentResources(root);
const compact=await stageCompactResources(root,development,output);
const config=await prepareMacInstaller({desktopRoot:root,runtimePkg,runtimeSha256,arch,output,version,development,compact});
const configFile=await writeStandaloneInstallerConfig(root,config,output,'macos-installer-config.json');
await build({targets:Platform.MAC.createTarget(['dmg','zip'],arch==='arm64'?Arch.arm64:Arch.x64),projectDir:root,config:configFile,publish:'never'});
await verifyCompactServer(path.join(output,arch==='arm64'?'mac-arm64':'mac','Mycellios Desktop.app/Contents/Resources/local-server'));
